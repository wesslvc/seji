/* 값 표기 — 단위별로 읽기 좋게 */
function statValText(set,v){
  if(set.unit==='명'){
    /* '1.02억'으로 반올림하면 필리핀·러시아처럼 붙어 있는 자리가 같은 값으로 보인다.
       '1억 250만' 꼴로 적어 두면 순위 차이가 눈에 들어온다. */
    if(v>=1e8){
      const eok=Math.floor(v/1e8), man=Math.round((v-eok*1e8)/1e4);
      return eok+'억'+(man?' '+man.toLocaleString()+'만':'')+' 명';
    }
    return Math.round(v/1e4).toLocaleString()+'만 명';
  }
  if(set.unit==='마리'){
    if(v>=1e8)return (v/1e8).toFixed(2)+'억 마리';
    return Math.round(v/1e4).toLocaleString()+'만 마리';
  }
  return v.toLocaleString()+' '+set.unit;
}

