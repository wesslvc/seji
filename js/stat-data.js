/* iso가 이 문항의 정답인지 — 'eu'는 회원국 아무 곳이나 인정한다 */
function statMatch(answerIso,clickedIso){
  if(answerIso==='eu')return EU_MEMBERS.indexOf(clickedIso)>=0;
  return answerIso===clickedIso;
}
/* 화면에 쓸 이름 */
function statIsoName(iso){
  if(iso==='eu')return '유럽 연합(EU)';
  return (typeof COUNTRIES!=='undefined'&&COUNTRIES[iso])?COUNTRIES[iso].k:iso;
}
/* 값 표기 — 단위별로 읽기 좋게 */
function statValText(set,v){
  if(set.unit==='명'){
    if(v>=1e8)return (v/1e8).toFixed(v>=1e9?1:2)+'억 명';
    return Math.round(v/1e4).toLocaleString()+'만 명';
  }
  if(set.unit==='마리'){
    if(v>=1e8)return (v/1e8).toFixed(2)+'억 마리';
    return Math.round(v/1e4).toLocaleString()+'만 마리';
  }
  return v.toLocaleString()+' '+set.unit;
}
